"""Scenario contracts. Records contain only Python values, never ORM instances."""
from dataclasses import dataclass
from datetime import datetime
from typing import Protocol, Callable
from app.domain.values import RequestContext, SystemContext, LessonCommand

Scope = RequestContext | SystemContext
Record = dict

class AuthRepository(Protocol):
    def session_identity(self, scope: SystemContext, token_hash: str) -> tuple | None: ...
    def find_user(self, scope: SystemContext, username: str) -> Record | None: ...
    def lock_user(self, context: RequestContext) -> Record: ...
    def update_profile(self, context: RequestContext, values: dict) -> Record: ...
    def create_session(self, context: RequestContext, values: dict) -> Record: ...
    def cap_sessions(self, context: RequestContext, old_hash: str, now: datetime) -> None: ...
    def delete_session(self, context: RequestContext, token_hash: str) -> None: ...

class DemoRepository(Protocol):
    def reserve_capacity(self, scope: SystemContext, now: datetime, replacing: int | None = None) -> None: ...
    def seed_workspace(self, scope: SystemContext, role: str, now: datetime) -> tuple[Record, Record]: ...
    def delete_workspace(self, context: RequestContext) -> None: ...
    def cleanup_expired(self, scope: SystemContext, now: datetime) -> int: ...

class CatalogRepository(Protocol):
    def list_directory(self, context: RequestContext, kind: str) -> list[Record]: ...
    def get_directory(self, context: RequestContext, kind: str, ident: int | None) -> Record | None: ...
    def create_directory(self, context: RequestContext, kind: str, values: dict) -> Record: ...
    def update_directory(self, context: RequestContext, kind: str, ident: int, values: dict) -> Record: ...
    def future_resources(self, context: RequestContext, kind: str, ident: int, now: datetime) -> list[Record]: ...
    def list_users(self, context: RequestContext) -> list[Record]: ...
    def create_user(self, context: RequestContext, values: dict) -> Record: ...
    def toggle_user(self, context: RequestContext, ident: int) -> Record: ...
    def list_periods(self, context: RequestContext) -> list[Record]: ...
    def get_period(self, context: RequestContext, ident: int) -> Record: ...
    def create_period(self, context: RequestContext, values: dict) -> Record: ...

class ScheduleRepository(Protocol):
    def list_schedules(self, context: RequestContext) -> list[Record]: ...
    def get_schedule(self, context: RequestContext, ident: int) -> Record: ...
    def create_schedule(self, context: RequestContext, values: dict) -> Record: ...
    def has_lessons(self, context: RequestContext, ident: int) -> bool: ...
    def publish_schedule(self, context: RequestContext, ident: int) -> Record: ...
    def list_lessons(self, context: RequestContext, begin: datetime, finish: datetime, filters: dict, offset: int, limit: int) -> Record: ...
    def get_lesson(self, context: RequestContext, ident: int) -> Record: ...
    def conflicts(self, context: RequestContext, data: LessonCommand, exclude_id: int | None = None) -> list[Record]: ...
    def insert_lesson(self, context: RequestContext, values: dict) -> Record: ...
    def update_lesson(self, context: RequestContext, ident: int, values: dict) -> Record: ...
    def append_audit(self, context: RequestContext, action: str, lesson: Record | None = None, schedule_id: int | None = None, before: Record | None = None, reason: str = '') -> None: ...
    def history(self, context: RequestContext, ident: int) -> list[Record]: ...
    def find_series(self, context: RequestContext, request_key: str) -> Record | None: ...
    def create_series(self, context: RequestContext, request_key: str, digest: str) -> Record: ...
    def series_lessons(self, context: RequestContext, ident: int) -> list[int]: ...

class UnitOfWork(Protocol):
    auth: AuthRepository
    demo: DemoRepository
    catalog: CatalogRepository
    schedules: ScheduleRepository
    def __enter__(self) -> 'UnitOfWork': ...
    def __exit__(self, *args) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
    def lock_workspace(self, workspace_id: int, timeout_ms: int = 2000) -> None: ...
    def health(self) -> None: ...

UowFactory = Callable[[Scope], UnitOfWork]

@dataclass(frozen=True)
class LimitBucket:
    name: str
    subject: str  # opaque digest generated by the application
    limit: int
    window_seconds: int

@dataclass(frozen=True)
class LimitDecision:
    allowed: bool
    retry_after: int = 0

class MutationLimiter(Protocol):
    def consume(self, policy: str, buckets: list[LimitBucket]) -> LimitDecision: ...

class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password: str, stored: str) -> bool: ...
    dummy_hash: str

class TokenService(Protocol):
    def new(self) -> str: ...
    def digest(self, raw: str) -> str: ...

class Clock(Protocol):
    def now(self) -> datetime: ...
